"""Write src/unicode_tables.rs: the character classes recog's Python code relies on.

Python's str methods follow the Unicode database of the interpreter (15.0.0 for 3.12);
Rust's std follows its own. The ported code needs Python's answer, so the tables come
from Python itself:

    venv-gigaam/bin/python rust/recog-core/gen_unicode_tables.py
"""

import sys
import unicodedata
from pathlib import Path

OUT = Path(__file__).parent / "src" / "unicode_tables.rs"


def ranges(predicate):
    result, start = [], None
    for code in range(sys.maxunicode + 2):
        inside = code <= sys.maxunicode and predicate(chr(code))
        if inside and start is None:
            start = code
        elif not inside and start is not None:
            result.append((start, code - 1))
            start = None
    return result


def table(name, doc, items):
    body = "".join(f"    (0x{a:X}, 0x{b:X}),\n" for a, b in items)
    return f"/// {doc}\npub const {name}: &[(u32, u32)] = &[\n{body}];\n\n"


def rust_str(text):
    return '"' + "".join(f"\\u{{{ord(c):x}}}" for c in text) + '"'


def main():
    chars = [chr(code) for code in range(sys.maxunicode + 1)]
    folds = [(ord(c), c.casefold()) for c in chars if c.casefold() != c]
    # int() and float() read every Unicode decimal digit; each script's digits are
    # ten consecutive code points starting at its zero.
    zeros = [ord(c) for c in chars if unicodedata.decimal(c, None) == 0]
    assert all(unicodedata.decimal(chr(z + d), None) == d for z in zeros for d in range(10))
    assert sum(unicodedata.decimal(c, None) is not None for c in chars) == 10 * len(zeros)
    out = (
        "//! Generated by gen_unicode_tables.py from Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}); do not edit.\n\n"
        + table(
            "OTHER",
            "Characters whose general category starts with C (`unicodedata.category`).",
            ranges(lambda c: unicodedata.category(c).startswith("C")),
        )
        + table(
            "NONPRINTABLE",
            "Characters for which `str.isprintable()` is false.",
            ranges(lambda c: not c.isprintable()),
        )
        + table("SPACE", "Characters for which `str.isspace()` is true.", ranges(str.isspace))
        + "/// The zero of every run of ten Unicode decimal digits (`unicodedata.decimal`).\n"
        + "pub const DECIMAL_ZEROS: &[u32] = &[\n"
        + "".join(f"    0x{z:X},\n" for z in zeros)
        + "];\n\n"
        + "/// `str.casefold()` of every character it changes, sorted by code point.\n"
        + "pub const CASEFOLD: &[(u32, &str)] = &[\n"
        + "".join(f"    (0x{code:X}, {rust_str(folded)}),\n" for code, folded in folds)
        + "];\n"
    )
    OUT.write_text(out)


if __name__ == "__main__":
    main()
